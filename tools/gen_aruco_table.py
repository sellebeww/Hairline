"""Generates packages/hairline_core/lib/src/aruco_bits.dart from OpenCV (DICT_4X4_50, ids 0..47).

Run: python3 -m venv v && v/bin/pip install opencv-contrib-python-headless numpy
     v/bin/python tools/gen_aruco_table.py > packages/hairline_core/lib/src/aruco_bits.dart
Each marker is a 16-bit integer: the 4x4 inner bits row by row, top-left bit first
(most significant), 1 = white cell. The 1-cell black border is implied.
"""
import cv2

D = cv2.aruco.getPredefinedDictionary(cv2.aruco.DICT_4X4_50)
rows = []
for marker_id in range(48):
    img = cv2.aruco.generateImageMarker(D, marker_id, 6, borderBits=1)
    assert (img[0, :] == 0).all() and (img[5, :] == 0).all() and (img[:, 0] == 0).all() and (img[:, 5] == 0).all()
    bits = 0
    for r in range(4):
        for c in range(4):
            bits = (bits << 1) | (1 if img[1 + r, 1 + c] > 127 else 0)
    rows.append(bits)

print("// Copyright (c) 2026 Vassel Goleyu. MIT License.")
print(f"// GENERATED by tools/gen_aruco_table.py with OpenCV {cv2.__version__}. Do not edit.")
print()
print("/// Inner 4x4 bits of ArUco `DICT_4X4_50` markers 0..47 (ids of sheets 0..11), row by row,")
print("/// top-left bit most significant, 1 = white cell. The black border cell ring is implied.")
print("const List<int> aruco4x4Bits = [")
for i in range(0, 48, 6):
    print("  " + ", ".join(f"0x{b:04X}" for b in rows[i:i + 6]) + ",")
print("];")
